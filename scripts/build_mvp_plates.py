"""
Build the data bundle used by the DeepHalo / ADLMS web MVP.

Reads real, hand-labelled plates from Antibiogram_demo/Train (YOLO .txt
annotations + classes.txt), copies the images into mvp_web/sample_plates/ and
writes mvp_web/plates_data.js, so the UI works from file:// or any static host.

Usage:  python build_mvp_plates.py
"""
import json
import shutil
from pathlib import Path

from PIL import Image

BASE = Path(__file__).resolve().parent.parent
# Look for dataset in data/Antibiogram_demo with fallback to Antibiogram_demo
TRAIN = BASE / "data" / "Antibiogram_demo" / "Train"
if not TRAIN.exists():
    TRAIN = BASE / "Antibiogram_demo" / "Train"
OUT_DIR = BASE / "mvp_web"
IMG_DIR = OUT_DIR / "sample_plates"

# Plates picked from the training split (all three carry full annotations).
PLATES = [
    {
        "key": "gn_a",
        "stem": "IMG20230321083329",
        "title": "Placa 01 · Panel Gram negativo",
        "short": "GN-01",
        "group": "Enterobacterales",
        "sampleId": "2026102508332914",
        "organism": "Escherichia coli (ATCC 25922)",
    },
    {
        "key": "gp_a",
        "stem": "IMG20230320104623",
        "title": "Placa 02 · Panel Gram positivo",
        "short": "GP-02",
        "group": "Staphylococcus aureus",
        "sampleId": "2026102510462381",
        "organism": "Staphylococcus aureus (ATCC 29213)",
    },
    {
        "key": "gn_b",
        "stem": "IMG20230321083340",
        "title": "Placa 03 · Panel mixto",
        "short": "GN-03",
        "group": "Enterobacterales",
        "sampleId": "2026102508334092",
        "organism": "Klebsiella pneumoniae (BLEE)",
    },
]


def load_classes():
    names = [l.strip() for l in (TRAIN / "classes.txt").read_text().splitlines()]
    return [n for n in names if n]


def parse_label_file(path):
    rows = []
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) != 5:
            continue
        cls = int(parts[0])
        x, y, w, h = map(float, parts[1:])
        rows.append((cls, x, y, w, h))
    return rows


def main():
    classes = load_classes()
    zone_ids = {i for i, n in enumerate(classes) if n.lower().replace(" ", "_") == "inhibition_zone"}
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    # Remove previous generated/obsolete samples
    for old in IMG_DIR.glob("*.jpg"):
        old.unlink()

    bundle = []
    for p in PLATES:
        src = TRAIN / f"{p['stem']}.jpg"
        dst = IMG_DIR / f"{p['key']}.jpg"
        shutil.copyfile(src, dst)
        with Image.open(src) as im:
            width, height = im.size

        rows = parse_label_file(TRAIN / f"{p['stem']}.txt")
        discs, zones = [], []
        for cls, x, y, w, h in rows:
            item = {"x": x, "y": y, "w": w, "h": h}
            if cls in zone_ids:
                zones.append(item)
            else:
                item["code"] = classes[cls]
                discs.append(item)

        bundle.append(
            {
                "key": p["key"],
                "title": p["title"],
                "short": p["short"],
                "group": p["group"],
                "sampleId": p["sampleId"],
                "organism": p["organism"],
                "image": f"sample_plates/{p['key']}.jpg",
                "source": f"Antibiogram_demo/Train/{p['stem']}.jpg",
                "width": width,
                "height": height,
                "discs": discs,
                "zones": zones,
            }
        )
        print(f"{p['key']}: {len(discs)} discs, {len(zones)} zones ({width}x{height})")

    js = "// AUTO-GENERATED by build_mvp_plates.py — do not edit by hand.\n"
    js += "window.ADLMS_PLATES = " + json.dumps(bundle, indent=1) + ";\n"
    (OUT_DIR / "plates_data.js").write_text(js, encoding="utf-8")
    print("wrote", OUT_DIR / "plates_data.js")


if __name__ == "__main__":
    main()
